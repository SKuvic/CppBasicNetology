#include "Broom.h"

// Конструктор: передаем родителю Имя="Метла" и Скорость=20
Broom::Broom() : Air("Метла", 8.0) {}

// Реализуем уникальное изменение дистанции
double Broom::getDistanceCoefficient(double distance) const {
    double coefficient = 0.0;

    // Цикл увеличивает счетчик i (количество тысяч), пока (i * 1000) не превысит расстояние.
    // Например, для 5600:
    // i=1 (1000 <= 5600) -> +1%
    // ...
    // i=5 (5000 <= 5600) -> +1%
    // i=6 (6000 <= 5600) -> Ложь, цикл завершается.
    for (int i = 1; i * 1000.0 <= distance; i++) {
        coefficient += 0.01; // Прибавляем 1% за каждую полную тысячу
    }

    return coefficient;
}
